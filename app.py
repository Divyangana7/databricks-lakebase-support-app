@app.get("/healthz")
def healthz():
    """Health check for Databricks Apps."""
    return {"status": "ok"}, 200


@app.get("/")
def index():
    # Filter by status if a valid one is supplied; otherwise show everything.
    status_filter = request.args.get("status")
    if status_filter not in VALID_STATUSES:
        status_filter = None
    tickets = list_tickets(status_filter)
    counts, total = status_counts()
    return render_template(
        "index.html",
        tickets=tickets,
        status_labels=STATUS_LABELS,
        priority_labels=PRIORITY_LABELS,
        valid_priorities=VALID_PRIORITIES,
        counts=counts,
        total=total,
        active_status=status_filter,
    )


@app.post("/tickets")
def create_ticket():
    title = (request.form.get("title") or "").strip()
    created_by = (request.form.get("created_by") or "").strip()
    priority = (request.form.get("priority") or "medium").strip()
    if priority not in VALID_PRIORITIES:
        priority = "medium"

    if not title or not created_by:
        flash("A title and your name are both required to open a ticket.", "error")
        return redirect(url_for("index"))

    row = insert_returning(
        """
        INSERT INTO tickets (title, status, priority, created_by)
        VALUES (%s, 'open', %s, %s)
        RETURNING ticket_id
        """,
        (title, priority, created_by),
    )
    flash("Ticket created.", "success")
    return redirect(url_for("view_ticket", ticket_id=row["ticket_id"]))


@app.get("/tickets/<int:ticket_id>")
def view_ticket(ticket_id: int):
    ticket = get_ticket(ticket_id)
    if ticket is None:
        abort(404)
    messages = get_messages(ticket_id)
    return render_template(
        "ticket.html",
        ticket=ticket,
        messages=messages,
        valid_statuses=VALID_STATUSES,
        status_labels=STATUS_LABELS,
        valid_priorities=VALID_PRIORITIES,
        priority_labels=PRIORITY_LABELS,
    )


@app.post("/tickets/<int:ticket_id>/messages")
def add_message(ticket_id: int):
    if get_ticket(ticket_id) is None:
        abort(404)

    author = (request.form.get("author") or "").strip()
    message_text = (request.form.get("message_text") or "").strip()

    if not author or not message_text:
        flash("A name and a message are both required.", "error")
        return redirect(url_for("view_ticket", ticket_id=ticket_id))

    run_write(
        """
        INSERT INTO ticket_messages (ticket_id, author, message_text)
        VALUES (%s, %s, %s)
        """,
        (ticket_id, author, message_text),
    )
    flash("Message added.", "success")
    return redirect(url_for("view_ticket", ticket_id=ticket_id))


@app.post("/tickets/<int:ticket_id>/status")
def update_status(ticket_id: int):
    if get_ticket(ticket_id) is None:
        abort(404)

    new_status = (request.form.get("status") or "").strip()
    if new_status not in VALID_STATUSES:
        flash("That status is not allowed.", "error")
        return redirect(url_for("view_ticket", ticket_id=ticket_id))

    run_write(
        "UPDATE tickets SET status = %s WHERE ticket_id = %s",
        (new_status, ticket_id),
    )
    flash(f"Status updated to {STATUS_LABELS[new_status]}.", "success")
    return redirect(url_for("view_ticket", ticket_id=ticket_id))


@app.post("/tickets/<int:ticket_id>/priority")
def update_priority(ticket_id: int):
    if get_ticket(ticket_id) is None:
        abort(404)

    new_priority = (request.form.get("priority") or "").strip()
    if new_priority not in VALID_PRIORITIES:
        flash("That priority is not allowed.", "error")
        return redirect(url_for("view_ticket", ticket_id=ticket_id))

    run_write(
        "UPDATE tickets SET priority = %s WHERE ticket_id = %s",
        (new_priority, ticket_id),
    )
    flash(f"Priority set to {PRIORITY_LABELS[new_priority]}.", "success")
    return redirect(url_for("view_ticket", ticket_id=ticket_id))


@app.get("/tickets/<int:ticket_id>/delete")
def confirm_delete(ticket_id: int):
    ticket = get_ticket(ticket_id)
    if ticket is None:
        abort(404)
    message_count = len(get_messages(ticket_id))
    return render_template(
        "delete.html", ticket=ticket, message_count=message_count
    )


@app.post("/tickets/<int:ticket_id>/delete")
def delete_ticket(ticket_id: int):
    if get_ticket(ticket_id) is None:
        abort(404)
    # ticket_messages rows are removed automatically via ON DELETE CASCADE.
    run_write("DELETE FROM tickets WHERE ticket_id = %s", (ticket_id,))
    flash("Ticket deleted.", "success")
    return redirect(url_for("index"))


if __name__ == "__main__":
    # Create/upgrade tables on startup so a fresh instance works immediately.
    ensure_schema()
    # Databricks Apps substitutes DATABRICKS_APP_PORT into the run command; we
    # also read it here and fall back to 8000 (the Databricks Apps default).
    port = int(os.environ.get("DATABRICKS_APP_PORT", os.environ.get("PORT", "8000")))
    app.run(host="0.0.0.0", port=port)
